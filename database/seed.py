def seed_database() -> None:
    """Insert starter content. Safe to run on an empty or already-seeded database."""
    db = get_db()
    get_or_create_demo_student()

    question_count = db.execute("SELECT COUNT(*) AS c FROM quiz_questions").fetchone()["c"]
    if question_count == 0:
        db.executemany(
            """
            INSERT INTO quiz_questions (
                track, topic, question_text, option_a, option_b, option_c, option_d,
                correct_option, explanation
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            [
                (
                    q["track"],
                    q["topic"],
                    q["question_text"],
                    q["option_a"],
                    q["option_b"],
                    q["option_c"],
                    q["option_d"],
                    q["correct_option"],
                    q["explanation"],
                )
                for q in QUESTIONS
            ],
        )

    resource_count = db.execute("SELECT COUNT(*) AS c FROM learning_resources").fetchone()["c"]
    if resource_count == 0:
        db.executemany(
            """
            INSERT INTO learning_resources (
                track, topic, title, description, difficulty, resource_type, url
            ) VALUES (?, ?, ?, ?, ?, ?, ?)
            """,
            [
                (
                    r["track"],
                    r["topic"],
                    r["title"],
                    r["description"],
                    r["difficulty"],
                    r["resource_type"],
                    r["url"],
                )
                for r in RESOURCES
            ],
        )

    db.commit()
